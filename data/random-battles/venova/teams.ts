export class RandomVenovaTeams extends RandomTeams {
	override randomTeam(): RandomTeamsTypes.RandomSet[] {
		const team: RandomTeamsTypes.RandomSet[] = [];
		const pool = [...CUSTOM_SPECIES];
		this.prng.shuffle(pool);
		const teamSize = Math.min(6, pool.length);

		for (let i = 0; i < teamSize; i++) {
			const species = this.dex.species.get(pool[i]);
			team.push(this.customRandomSet(species));
		}
		return team;
	}

	customRandomSet(species: Species): RandomTeamsTypes.RandomSet {
		const learnset = this.dex.data.Learnsets[species.id]?.learnset || {};
		const allMoves = Object.keys(learnset);

		// simple manual shuffle+pick if .sample isn't right for your version:
		const shuffled = [...allMoves];
		this.prng.shuffle(shuffled);
		const chosenMoves = shuffled.slice(0, Math.min(4, shuffled.length));

		const abilities = Object.values(species.abilities).filter(Boolean) as string[];
		const ability = abilities[this.prng.random(abilities.length)];

		return {
			name: species.baseSpecies,
			species: species.name,
			gender: species.gender || '',
			moves: chosenMoves,
			ability,
			evs: {hp: 85, atk: 85, def: 85, spa: 85, spd: 85, spe: 85},
			ivs: {hp: 31, atk: 31, def: 31, spa: 31, spd: 31, spe: 31},
			item: '',
			level: 100,
			shiny: false,
			nature: 'Hardy',
		};
	}
}

